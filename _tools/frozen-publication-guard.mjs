#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {projectKanbanFromEvents} from '../_generator/lib/run-supervisor.mjs';
import {assertFrozenPublication} from '../_generator/lib/frozen-publication.mjs';
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const pointer=read('data/operations/active-production-run.json'),root='_candidate_site';
if(!/^\d{4}-\d{2}-\d{2}-run\d+$/.test(pointer.execution_key||'')) throw Error('execution_key_required');
const dir=path.join(root,'_records/edition-execution/events',pointer.execution_key);
const events=fs.readdirSync(dir).filter(p=>p.endsWith('.json')).map(p=>read(path.join(dir,p)));
const tasks=read('docs/operations/task-recovery-contracts.json').tasks;
const projection=projectKanbanFromEvents({tasks,events,execution_id:pointer.execution_id,edition_id:pointer.edition_id});
const manifest=read(path.join(root,'_records/editorial-handoff/publication-manifest.json'));
if(!/^\d{4}-\d{2}-\d{2}$/.test(manifest.edition_date||'')) throw Error('edition_date_required');
const pub=path.join(root,'_records/publication',manifest.edition_date);
const validated=fs.readdirSync(pub).filter(p=>p.endsWith('.json')).map(p=>read(path.join(pub,p)));
const baselineSha=execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim();
const result=assertFrozenPublication({pointer,branch:process.env.STAGING_REF,tasks:projection.tasks,events,manifest,validated,baselineSha});
const candidateSha=execFileSync('git',['-C',root,'rev-parse','HEAD'],{encoding:'utf8'}).trim();
if(process.env.EXPECTED_SHA && process.env.EXPECTED_SHA!==candidateSha) throw Error('frozen_dispatch_candidate_changed');
fs.writeFileSync('/tmp/frozen-publication.json',JSON.stringify({...result,baseline_sha:baselineSha,candidate_sha:candidateSha}));
console.log(JSON.stringify(result));
